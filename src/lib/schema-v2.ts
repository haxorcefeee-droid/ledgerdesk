  for (const statement of statements) {
    await db.exec(statement);
  }

  await addColumn(db, "accounts", "business_id INTEGER");
  await addColumn(db, "accounts", "folder_id INTEGER");
  await addColumn(db, "accounts", "control_kind TEXT");
  await addColumn(db, "cash_accounts", "business_id INTEGER");
  await addColumn(db, "cash_accounts", "currency TEXT DEFAULT 'USD'");
  await addColumn(db, "journal_entries", "business_id INTEGER");
  await addColumn(db, "journal_entries", "division_id INTEGER");
  await addColumn(db, "journal_entries", "project_id INTEGER");
  await addColumn(db, "journal_entries", "reference TEXT DEFAULT ''");
