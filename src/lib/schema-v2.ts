import type { Db, DbClient } from "./db";
import { DEFAULT_MODULES } from "./modules";

async function addColumn(db: DbClient, table: string, definition: string) {
  try {
    await db.exec(`ALTER TABLE ${table} ADD COLUMN ${definition}`);
  } catch {
    // already present
  }
}

